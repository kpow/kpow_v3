// Per-URL <title>, description, Open Graph and Twitter tags, written into the
// SPA's index.html before it's sent. Link-preview crawlers don't run
// JavaScript, so this is the only copy they see. The copy itself lives in
// client/src/lib/page-meta.ts, shared with the client's <SEO>.
//
// index.html marks the spot with <!--page-meta--> … <!--/page-meta-->.

const MARK = /<!--page-meta-->[\s\S]*?<!--\/page-meta-->/;
/** Data lookups never hold a page up longer than this; past it the page gets the fixed copy. */
const DATA_TIMEOUT_MS = 1500;

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function withTimeout<T>(p: Promise<T>): Promise<T | null> {
  return Promise.race([p, new Promise<null>((r) => setTimeout(() => r(null), DATA_TIMEOUT_MS))]).catch(() => null);
}

/** Origin for absolute image URLs: SITE_URL, else kpow.xyz in production, else whatever host served the request. */
export function siteOrigin(req: Request) {
  if (process.env.SITE_URL) return process.env.SITE_URL.replace(/\/$/, "");
  if (process.env.NODE_ENV === "production") return SITE.origin;
  return `${req.protocol}://${req.get("host")}`;
}

// ------------------------------------------------------------------ data

/** builds.json, re-read when the file changes (it's regenerated by `npm run buildlog`). */
let builds: { mtime: number; list: BuildLike[] } | null = null;
function loadBuilds(publicDir: string): BuildLike[] {
  const file = path.join(publicDir, "builds.json");
  try {
    const mtime = fs.statSync(file).mtimeMs;
    if (!builds || builds.mtime !== mtime) {
      builds = { mtime, list: JSON.parse(fs.readFileSync(file, "utf-8")).builds ?? [] };
    }
    return builds.list;
  } catch {
    return [];
  }
}

/** Width and height of a local JPEG or PNG, from its header. */
const sizes = new Map<string, { w: number; h: number } | undefined>();
function imageSize(file: string): { w: number; h: number } | undefined {
  if (sizes.has(file)) return sizes.get(file);
  let size: { w: number; h: number } | undefined;
  try {
    const fd = fs.openSync(file, "r");
    const buf = Buffer.alloc(64 * 1024);
    const n = fs.readSync(fd, buf, 0, buf.length, 0);
    fs.closeSync(fd);
    if (buf.readUInt32BE(0) === 0x89504e47) {
      size = { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
    } else if (buf[0] === 0xff && buf[1] === 0xd8) {
      // walk the JPEG segments to the first start-of-frame marker
      let i = 2;
      while (i + 9 < n) {
        if (buf[i] !== 0xff) break;
        const marker = buf[i + 1];
        const len = buf.readUInt16BE(i + 2);
        if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
          size = { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
          break;
        }
        i += 2 + len;
      }
    }
  } catch {
    size = undefined;
  }
  sizes.set(file, size);
  return size;
}

/** The phashboard summary is small but sits in a big cached row; keep just the numbers for 10 minutes. */
let phash: { at: number; summary: any; pf: any } | null = null;
async function phashSummary() {
  if (phash && Date.now() - phash.at < 10 * 60_000) return phash;
  const part = await loadPart("core"); // read only: never starts a rebuild
  if (!part) return null;
  phash = { at: Date.now(), summary: part.body?.summary ?? null, pf: part.body?.pf_summary ?? null };
  return phash;
}

/** The meta for one request path, with data where the page has it. */
export async function metaForRequest(urlPath: string, publicDir: string): Promise<PageMeta> {
  const p = urlPath.length > 1 ? urlPath.replace(/\/+$/, "") : urlPath;

  let m: RegExpMatchArray | null;
  if ((m = p.match(/^\/builds\/([^/]+)$/)) && m[1] !== "recently") {
    const slug = decodeURIComponent(m[1]);
    const build = loadBuilds(publicDir).find((b) => b.slug === slug) ?? null;
    const hero = build?.hero && !/^https?:/.test(build.hero) ? imageSize(path.join(publicDir, build.hero)) : undefined;
    return buildMeta(build, hero);
  }
  if (p === "/shows") {
    const data = (await withTimeout(publicShows())) as ShowzLike | null;
    return showsMeta(data);
  }
  if ((m = p.match(/^\/phashboard(?:\/([^/]+))?$/))) {
    const s = await withTimeout(phashSummary());
    return phashboardMeta(m[1], s?.summary, s?.pf);
  }
  return metaForPath(p);
}

// ------------------------------------------------------------------ html

/** index.html with this page's tags in place of the <!--page-meta--> block. */
export function injectMeta(html: string, meta: PageMeta, urlPath: string, origin: string) {
  const tags = headTags(meta, urlPath, origin)
    .map(({ tag, attrs }) => {
      const a = Object.entries(attrs).map(([k, v]) => `${k}="${esc(v)}"`).join(" ");
      return `<${tag} data-rh="true" ${a} />`;
    })
    .join("\n    ");
  const block = `<title>${esc(fullTitle(meta))}</title>\n    ${tags}`;
  return MARK.test(html) ? html.replace(MARK, block) : html.replace(/<title>[\s\S]*?<\/title>/, block);
}

/** index.html for this request: the right tags, a 404 status for unknown paths, never cached stale. */
export async function renderIndex(req: Request, template: string, publicDir: string) {
  // the SPA fallback is mounted at "*", so req.path is "/" there; use the original URL
  const urlPath = req.originalUrl.split("?")[0] || "/";
  let meta: PageMeta;
  try {
    meta = await metaForRequest(urlPath, publicDir);
  } catch (e) {
    console.error("[page-meta]", urlPath, e);
    meta = metaForPath(urlPath);
  }
  return {
    status: meta === NOT_FOUND ? 404 : 200,
    html: injectMeta(template, meta, urlPath, siteOrigin(req)),
  };
}

// ------------------------------------------------------------------ sitemap

/** /sitemap.xml: every public page, the phashboard tabs and each build. robots.txt points here. */
export function registerSitemap(app: Express, publicDir: string) {
  app.get("/sitemap.xml", (_req, res) => {
    const paths = [
      ...Object.entries(STATIC_PAGES).filter(([, m]) => !m.noindex).map(([p]) => p),
      ...Object.keys(PHASHBOARD_TABS).map((t) => `/phashboard/${t}`),
      ...loadBuilds(publicDir).map((b) => `/builds/${encodeURIComponent(b.slug)}`),
    ];
    const urls = paths.map((p) => `  <url><loc>${esc(SITE.origin + p)}</loc></url>`).join("\n");
    res
      .type("application/xml")
      .set("Cache-Control", "public, max-age=3600")
      .send(`<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);
  });
}

/** Requests for files (hashed bundles, images) that don't exist get a 404, not the SPA. */
export const looksLikeFile = (p: string) =>
  p.startsWith("/assets/") || /\.(js|mjs|css|map|json|png|jpe?g|gif|svg|webp|avif|ico|mp4|webm|woff2?|ttf|txt|xml)$/i.test(p);
